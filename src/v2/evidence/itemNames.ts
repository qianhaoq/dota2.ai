/** Humanize an unknown slug (`blade_mail` → `Blade mail`). */
export function humanizeItemSlug(slug: string): string {
  const words = slug.replaceAll('_', ' ');
  return words.charAt(0).toUpperCase() + words.slice(1);
}

/** Localized item label; unknown slugs fall back to humanized English. */
export function itemDisplayName(slug: string, lang: ItemLang = 'en'): string {
  const entry = ITEM_NAMES[slug];
  if (entry) return entry[lang];
  return humanizeItemSlug(slug);
}
